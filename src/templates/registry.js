// Matches the first path segment, so a couple's own link (/autumn/jane-joe) opens the same template.
export function findTemplate(pathname) {
  const root = `/${pathname.split('/').filter(Boolean)[0] ?? ''}`
  return templates.find((t) => t.path === root || t.aliases?.includes(root)) ?? null
}
